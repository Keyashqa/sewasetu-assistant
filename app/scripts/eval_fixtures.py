"""
LOCAL EVAL FIXTURES ONLY — the starting state some eval personas need (EVAL_PLAN.md §4).

Everything goes through the service layer, the same path a citizen's assistant or the
officer at the keyboard takes; nothing is written with raw SQL.

  pending      file a PENDING application with an EVAL FIXTURE age proof
               (save_draft -> issue_upload_token -> attach_draft_document -> submit).
               `officer-pending` and `citizen-pending` are the same thing under the names
               the plan uses.
  decide-web   approve or reject one PENDING application as the officer on the web form
               (services.decide, channel web, officer admin).
  render-docs  write the age-proof images the personas upload, into --out.

Every generated image carries "EVAL FIXTURE - NOT A REAL DOCUMENT" across the middle;
document_uploads.source is 'eval_fixture'. Prints one JSON object on the last line.
Refuses to run unless PUBLIC_BASE_URL points at localhost / 127.0.0.1.

    docker compose exec -T app python /app/scripts/eval_fixtures.py pending \
        --mobile 9812000150 --name "Eval Sarbeswar Dutta" --dob 11/11/1951 --village Lakhipur
"""

import argparse
import io
import json
import os
import sys
from datetime import datetime
from urllib.parse import urlparse

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import app as portal            # noqa: E402,F401  must come before services/oauth
import services                 # noqa: E402

# The documents personas upload (evals/fixtures/docs/<file>), one per applicant.
PERSONA_DOCS = [
    ("p01.png", "Voter ID card", "Dulumoni Gogoi", "14/03/1956"),
    ("p02.png", "School leaving certificate", "Lakhi Bora", "05/01/1954"),
    ("p04a.png", "Voter ID card", "Jogen Phukan", "02/02/1950"),
    ("p04b.png", "Voter ID card", "Rupa Phukan", "19/07/1958"),
    ("p06.png", "Voter ID card", "Kamala Das", "01/01/1960"),
    ("p08.png", "Birth certificate", "Anjali Sonowal", "04/03/1963"),
    ("p11.png", "Voter ID card", "Hemanta Bordoloi", "08/12/1950"),
    ("p15.png", "Voter ID card", "Prabin Kalita", "05/11/1958"),
]


def local_only():
    host = urlparse(os.environ.get("PUBLIC_BASE_URL", "http://localhost:8000")).hostname
    return host in ("localhost", "127.0.0.1")


def fixture_png(kind, name, dob):
    """A PNG that cannot be mistaken for a real paper: the watermark first, fields over it."""
    from PIL import Image, ImageDraw, ImageFont
    w, h = 1400, 1000
    img = Image.new("RGB", (w, h), (246, 248, 252))
    d = ImageDraw.Draw(img)
    big, mid, small = (ImageFont.load_default(size=s) for s in (110, 34, 30))

    def centre(y, text, font, fill):
        box = d.textbbox((0, 0), text, font=font)
        d.text(((w - (box[2] - box[0])) // 2, y), text, font=font, fill=fill)

    centre(h // 2 - 110, "EVAL FIXTURE", big, (60, 60, 60))
    centre(h // 2 + 30, "NOT A REAL DOCUMENT - generated by eval_fixtures.py", mid, (60, 60, 60))
    d.rectangle([30, 30, w - 30, h - 30], outline=(120, 120, 120), width=4)
    for i, t in enumerate(["%s (eval fixture)" % kind, "Name: %s" % name, "Date of birth: %s" % dob]):
        d.text((70, 70 + i * 48), t, font=small, fill=(20, 40, 110))
    out = io.BytesIO()
    img.save(out, "PNG")
    return out.getvalue()


def cmd_pending(a):
    fields = {"full_name": a.name, "date_of_birth": a.dob, "village": a.village,
              "bank_account": a.account, "ifsc": a.ifsc, "gender": a.gender,
              "marital_status": a.marital}
    if a.block:
        fields["block"] = a.block
    if a.husband:
        fields["husband_name"] = a.husband
    services.clear_draft(a.mobile)
    saved = services.save_draft(a.mobile, fields)
    tok = services.issue_upload_token(a.mobile)
    data = fixture_png("Voter ID card", a.name, a.dob)
    doc = services.attach_draft_document(tok["token"], "eval-fixture-%s.png" % a.mobile,
                                         io.BytesIO(data), source="eval_fixture")
    if doc["status"] != "ok":
        return {"status": "error", "step": "attach", "detail": doc}
    res = services.submit(a.mobile, True)
    if res["status"] != "ok":
        return {"status": "error", "step": "submit", "detail": res, "problems": saved.get("problems")}
    return {"status": "ok", "id": res["id"], "application_no": res["application_no"],
            "mobile": a.mobile, "sha256": doc["sha256"]}


def cmd_decide_web(a):
    res = services.decide(a.id, a.decision, a.reason, a.note, portal.ADMIN_USERNAME, "web")
    return {k: res.get(k) for k in ("status", "decision", "id", "application_no", "note", "sms_sent")}


def cmd_render_docs(a):
    os.makedirs(a.out, exist_ok=True)
    written = []
    for fname, kind, name, dob in PERSONA_DOCS:
        with open(os.path.join(a.out, fname), "wb") as f:
            f.write(fixture_png(kind, name, dob))
        written.append(fname)
    return {"status": "ok", "written": written, "generated_at": datetime.now().isoformat(timespec="seconds")}


def main():
    ap = argparse.ArgumentParser(description="Eval fixtures (local only).")
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("pending", "officer-pending", "citizen-pending"):
        p = sub.add_parser(name)
        p.add_argument("--mobile", required=True)
        p.add_argument("--name", required=True)
        p.add_argument("--dob", required=True, help="DD/MM/YYYY")
        p.add_argument("--village", required=True)
        p.add_argument("--block")
        p.add_argument("--account", default="40011223344")
        p.add_argument("--ifsc", default="SBIN0003077")
        p.add_argument("--gender", default="Male")
        p.add_argument("--marital", default="Married")
        p.add_argument("--husband")
        p.set_defaults(fn=cmd_pending)
    p = sub.add_parser("decide-web")
    p.add_argument("--id", type=int, required=True)
    p.add_argument("--decision", choices=["APPROVED", "REJECTED"], required=True)
    p.add_argument("--reason", default="")
    p.add_argument("--note", default="")
    p.set_defaults(fn=cmd_decide_web)
    p = sub.add_parser("render-docs")
    p.add_argument("--out", required=True)
    p.set_defaults(fn=cmd_render_docs)
    a = ap.parse_args()
    if not local_only():
        print(json.dumps({"status": "refused", "detail": "PUBLIC_BASE_URL is %r, not localhost/127.0.0.1"
                          % os.environ.get("PUBLIC_BASE_URL")}))
        return 2
    out = a.fn(a)
    print(json.dumps(out, ensure_ascii=False))
    return 0 if out.get("status") == "ok" else 1


if __name__ == "__main__":
    sys.exit(main())

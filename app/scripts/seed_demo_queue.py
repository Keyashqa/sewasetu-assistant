# -*- coding: utf-8 -*-
"""
LOCAL DEMO DATA ONLY — puts clean, pending work in the officer's queue on a local stack.

Creates N pending applications through the service layer, exactly the path a citizen's
assistant takes (services.save_draft -> issue_upload_token -> attach_draft_document ->
submit). It writes nothing with raw SQL.

Every synthetic applicant needs an age proof, so this script generates one. A generated
document must never be mistakable for a citizen's real paper:
  - every image carries "SAMPLE - DEMO DATA" in large dark text across the middle, plus
    "not a real document — generated by seed_demo_queue.py" and the generation time; the
    watermark is drawn first and the certificate fields over it;
  - document_uploads.source is 'demo_seed', which get_application and view_age_proof show;
  - mobiles are confined to 9000001001-9000001099 and names start with "Demo";
  - it refuses to run unless PUBLIC_BASE_URL points at localhost / 127.0.0.1.

Run it in the app container (the uploads volume is read-only in the mcp container):
    docker compose exec app python /app/scripts/seed_demo_queue.py --count 8
"""

import argparse
import io
import os
import random
import sys
from datetime import date, datetime
from urllib.parse import urlparse

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import app as portal            # noqa: E402,F401  must come before services/oauth
import services                 # noqa: E402

BANNER = "LOCAL DEMO DATA — do not run against the deployment"
MOBILE_FIRST, MOBILE_LAST = 9000001001, 9000001099
FIRST_NAMES = ["Anima", "Bhabesh", "Champa", "Dilip", "Gitali", "Hemanta", "Jonali", "Kamal",
               "Lakhi", "Mohan", "Nirmala", "Pranab", "Rina", "Sanjib", "Tara", "Utpal"]
SURNAMES = ["Bora", "Das", "Gogoi", "Hazarika", "Kalita", "Phukan", "Saikia", "Sonowal"]
IFSCS = ["SBIN0003077", "UTBI0PUR281", "CNRB0004417", "PUNB0123400"]


def local_only():
    host = urlparse(os.environ.get("PUBLIC_BASE_URL", "http://localhost:8000")).hostname
    return host in ("localhost", "127.0.0.1")


def demo_age_proof(name, dob, mobile, generated_at):
    """A PNG that is unmistakably demo data: the watermark first, the fields over it."""
    from PIL import Image, ImageDraw, ImageFont
    w, h = 1400, 1000
    img = Image.new("RGB", (w, h), (250, 248, 240))
    d = ImageDraw.Draw(img)
    big, mid, small = (ImageFont.load_default(size=s) for s in (120, 34, 30))

    def centre(y, text, font, fill):
        box = d.textbbox((0, 0), text, font=font)
        d.text(((w - (box[2] - box[0])) // 2, y), text, font=font, fill=fill)

    # ASCII hyphens: Pillow's built-in font has no en/em dash glyphs
    centre(h // 2 - 110, "SAMPLE - DEMO DATA", big, (60, 60, 60))
    centre(h // 2 + 40, "not a real document - generated by seed_demo_queue.py", mid, (60, 60, 60))
    centre(h // 2 + 90, "generated %s UTC" % generated_at.strftime("%d/%m/%Y %H:%M"), mid, (60, 60, 60))
    d.rectangle([30, 30, w - 30, h - 30], outline=(120, 120, 120), width=4)
    fields = ["Birth certificate (demo)", "Name: %s" % name,
              "Date of birth: %s" % dob.strftime("%d/%m/%Y"), "Mobile on file: %s" % mobile]
    for i, t in enumerate(fields):
        d.text((70, 70 + i * 48), t, font=small, fill=(20, 40, 110))
    out = io.BytesIO()
    img.save(out, "PNG")
    out.seek(0)
    return out


def free_mobiles(count):
    """The first `count` mobiles in the demo range with no active application."""
    out = []
    for m in range(MOBILE_FIRST, MOBILE_LAST + 1):
        e = services.eligibility(str(m))
        if not e["existing"]:
            out.append(str(m))
            if len(out) == count:
                break
    return out


def main():
    ap = argparse.ArgumentParser(description="Seed pending demo applications (local only).")
    ap.add_argument("--count", type=int, default=8)
    ap.add_argument("--seed", type=int, default=None, help="random seed for repeatable data")
    args = ap.parse_args()
    print(BANNER)
    if not local_only():
        print("Refusing: PUBLIC_BASE_URL is %r, not localhost/127.0.0.1."
              % os.environ.get("PUBLIC_BASE_URL"))
        return 2
    if not 1 <= args.count <= MOBILE_LAST - MOBILE_FIRST + 1:
        print("--count must be between 1 and %d" % (MOBILE_LAST - MOBILE_FIRST + 1))
        return 2
    rnd = random.Random(args.seed)
    villages = sorted(services.VILLAGES)
    mobiles = free_mobiles(args.count)
    if len(mobiles) < args.count:
        print("Only %d free demo mobiles left in %d-%d." % (len(mobiles), MOBILE_FIRST, MOBILE_LAST))
    today = portal.now_ist().date()
    generated_at = datetime.now()
    filed = 0
    for mobile in mobiles:
        name = "Demo %s %s" % (rnd.choice(FIRST_NAMES), rnd.choice(SURNAMES))
        age = rnd.randint(61, 85)
        dob = date(today.year - age, rnd.randint(1, 12), rnd.randint(1, 28))
        village = villages[filed % len(villages)]
        services.clear_draft(mobile)
        saved = services.save_draft(mobile, {
            "full_name": name, "date_of_birth": dob.strftime("%d/%m/%Y"), "village": village,
            "bank_account": "".join(rnd.choice("0123456789") for _ in range(12)),
            "ifsc": rnd.choice(IFSCS), "gender": rnd.choice(["Female", "Male"])})
        tok = services.issue_upload_token(mobile)
        doc = services.attach_draft_document(
            tok["token"], "demo-age-proof-%s.png" % mobile,
            demo_age_proof(name, dob, mobile, generated_at), source="demo_seed")
        res = services.submit(mobile, True)
        if res["status"] != "ok":
            print("  %s  NOT FILED: %s %s %s" % (mobile, res["status"], saved["problems"],
                                               res.get("errors") or res.get("missing") or ""))
            continue
        filed += 1
        print("  %s  %s  %-26s %-15s %-14s doc %s… (%d bytes)" % (
            mobile, res["application_no"], name, village, services.VILLAGES[village],
            doc["sha256"][:12], doc["byte_size"]))
    print("%d demo application(s) filed. %s" % (filed, BANNER))
    return 0 if filed == len(mobiles) else 1


if __name__ == "__main__":
    sys.exit(main())
